    private void daftarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_daftarButtonActionPerformed
        String npm = npmField.getText().trim();
        String nama = namaField.getText().trim();
        String prodi = (String) prodiCombo.getSelectedItem();
        String jenis = mahasiswaRadio.isSelected() ? "Mahasiswa"
                : (dosenRadio.isSelected() ? "Dosen" : "Umum");
        String email = emailField.getText().trim();
        String hp = hpField.getText().trim();
        String alamat = alamatTextArea.getText().trim();

        if (npm.isEmpty() || nama.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Mohon lengkapi NPM dan Nama lengkap!",
                    "Peringatan",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        String ringkasan = String.format(
                "Pendaftaran Berhasil!\n\n"
                + "NPM: %s\n"
                + "Nama: %s\n"
                + "Program Studi: %s\n"
                + "Jenis Anggota: %s\n"
                + "Email: %s\n"
                + "Nomor HP: %s\n"
                + "Alamat: %s",
                npm, nama, prodi, jenis, email, hp, alamat
        );

        JOptionPane.showMessageDialog(this, ringkasan, "Ringkasan Pendaftaran Anggota", JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_daftarButtonActionPerformed

