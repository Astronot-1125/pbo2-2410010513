    private void simpanButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_simpanButtonActionPerformed
        // 1. Validasi NPM
        String npm = npmField.getText().trim();
        if (!npm.matches("\\d{10}")) {
            tampilkanKesalahan("NPM harus 10 digit angka", npmField);
            return;
        }
        if (tableModel.apakahNpmSudahAda(npm)) {
            tampilkanKesalahan("NPM " + npm + " sudah terdaftar", npmField);
            return;
        }

        // 2. Validasi Nama
        String nama = namaField.getText().trim();
        if (nama.isEmpty()) {
            tampilkanKesalahan("Nama wajib diisi", namaField);
            return;
        }

        // 3. Validasi Nilai Tugas
        int tugas;
        try {
            tugas = Integer.parseInt(tugasField.getText().trim());
            if (tugas < 0 || tugas > 100) {
                tampilkanKesalahan("Nilai Tugas harus angka bulat 0 sampai 100", tugasField);
                return;
            }
        } catch (NumberFormatException ex) {
            tampilkanKesalahan("Nilai Tugas harus angka bulat 0 sampai 100", tugasField);
            return;
        }

        // 4. Validasi Nilai UTS
        int uts;
        try {
            uts = Integer.parseInt(utsField.getText().trim());
            if (uts < 0 || uts > 100) {
                tampilkanKesalahan("Nilai UTS harus angka bulat 0 sampai 100", utsField);
                return;
            }
        } catch (NumberFormatException ex) {
            tampilkanKesalahan("Nilai UTS harus angka bulat 0 sampai 100", utsField);
            return;
        }

        // 5. Validasi Nilai UAS
        int uas;
        try {
            uas = Integer.parseInt(uasField.getText().trim());
            if (uas < 0 || uas > 100) {
                tampilkanKesalahan("Nilai UAS harus angka bulat 0 sampai 100", uasField);
                return;
            }
        } catch (NumberFormatException ex) {
            tampilkanKesalahan("Nilai UAS harus angka bulat 0 sampai 100", uasField);
            return;
        }

        // Jika semua valid: buat data, simpan ke tabel, bersihkan form, dan perbarui ringkasan
        NilaiMahasiswa mhs = new NilaiMahasiswa(npm, nama, tugas, uts, uas);
        tableModel.tambah(mhs);

        bersihkanFormInput();
        pesanLabel.setText(" ");
        perbaruiRingkasan();
        npmField.requestFocusInWindow();
    }//GEN-LAST:event_simpanButtonActionPerformed

